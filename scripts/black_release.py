"""Supported retail releases of BLACK and their guest address layouts.

Every hard-coded guest address in this repository is written for the NTSC
release, which serves as the canonical layout. Other releases are described by
how their image differs from it, so hooks, manual functions and patches remain
single copies:

* Generated symbol names (sub_X, loc_X) are renamed back to canonical
  addresses after recompilation. Hooks and recomp_manual.c keep matching them.
* Literal guest values (MEM32(0x...), return addresses, callback pointers) must
  stay at the release's real address. generate.py translates them with
  ``Release.text`` and recomp_manual.c with ``BLACK_VA``.
"""
import re
from dataclasses import dataclass
from typing import Optional

TEXT_START = 0x11000
# First address after the canonical .text section (it ends at 0x217FAC).
CANONICAL_TEXT_END = 0x217FC0
# Translation stops at the end of the loaded image. Higher values are heap,
# stacks or hardware, which do not move between releases.
IMAGE_END = 0x600000


@dataclass(frozen=True)
class Release:
    name: str
    sha256: str
    # Canonical .text addresses up to text_cut_low keep their address and those
    # from text_cut_high move by text_shift. The inserted bytes lie between.
    text_cut_low: int = CANONICAL_TEXT_END
    text_cut_high: int = CANONICAL_TEXT_END
    text_shift: int = 0
    # Shift of every section after .text (they are 32-byte aligned).
    post_shift: int = 0
    xbe_language_banks: tuple = ("US",)

    @property
    def canonical(self):
        return self.text_shift == 0 and self.post_shift == 0

    def to_guest(self, va):
        """Translate a canonical (NTSC) guest address to this release."""
        if self.canonical or not TEXT_START <= va < IMAGE_END:
            return va
        if va >= CANONICAL_TEXT_END:
            return va + self.post_shift
        if va <= self.text_cut_low:
            return va
        if va >= self.text_cut_high:
            return va + self.text_shift
        raise ValueError(
            f"0x{va:06X} lies in the {self.name} insertion window "
            f"0x{self.text_cut_low:06X}-0x{self.text_cut_high:06X}; "
            "find the exact insertion point before using it")

    def to_canonical(self, va) -> Optional[int]:
        """Inverse of to_guest. None for code with no canonical counterpart."""
        if self.canonical or not TEXT_START <= va < IMAGE_END:
            return va
        if va >= CANONICAL_TEXT_END + self.post_shift:
            return va - self.post_shift
        if va <= self.text_cut_low:
            return va
        if va >= self.text_cut_high + self.text_shift:
            return va - self.text_shift
        return None

    def text(self, template):
        """Fill {0x...} placeholders with this release's address.

        The digit count and an optional 'u' suffix are preserved, so a hook
        marker matches the recompiler's formatting of the same constant.
        """
        def repl(match):
            digits, suffix = match[1], match[2]
            value = self.to_guest(int(digits, 16))
            return f"0x{value:0{len(digits)}X}{suffix}"
        return re.sub(r"\{0x([0-9A-Fa-f]+)(u?)\}", repl, template)

    def rename_symbols(self, text):
        """Rename generated sub_X / loc_X symbols to canonical addresses.

        Code inside the insertion window has no canonical address. It keeps
        its own address with a _pal suffix, so no name can collide.
        """
        if self.canonical:
            return text

        def repl(match):
            va = int(match[2], 16)
            canonical = self.to_canonical(va)
            if canonical is None:
                return f"{match[1]}_{va:08X}_{self.name}"
            return f"{match[1]}_{canonical:08X}"
        return SYMBOL.sub(repl, text)

    def guest_symbols(self, text):
        """Rename canonical sub_X names to this release's addresses."""
        if self.canonical:
            return text
        return re.sub(r"\bsub_([0-9A-Fa-f]{8})(?![0-9A-Fa-f])",
                      lambda m: f"sub_{self.to_guest(int(m[1], 16)):08X}", text)

    def header(self):
        """C definitions consumed by src/black_release.h."""
        pal = 0 if self.canonical else 1
        return (
            "/* Generated by scripts/generate.py for the local XBE. Do not edit. */\n"
            "#pragma once\n"
            f"#define BLACK_RELEASE_NAME \"{self.name}\"\n"
            f"#define BLACK_RELEASE_PAL {pal}\n"
            f"#define BLACK_TEXT_CUT_LOW 0x{self.text_cut_low:06X}u\n"
            f"#define BLACK_TEXT_CUT_HIGH 0x{self.text_cut_high:06X}u\n"
            f"#define BLACK_TEXT_SHIFT 0x{self.text_shift:02X}u\n"
            f"#define BLACK_POST_SHIFT 0x{self.post_shift:02X}u\n")


SYMBOL = re.compile(r"\b(sub|loc)_([0-9A-Fa-f]{8})(?![0-9A-Fa-f])")
C_LITERAL = re.compile(r"(?<![\w.])0x([0-9A-Fa-f]+)[uUlL]*(?![\w.])")


def _mask_comments_and_strings(text):
    """Blank C comments and string/char literals, keeping offsets and lines."""
    out, i = [], 0
    while i < len(text):
        if text.startswith("/*", i):
            end = text.find("*/", i + 2)
            end = len(text) if end < 0 else end + 2
        elif text.startswith("//", i):
            end = text.find("\n", i)
            end = len(text) if end < 0 else end
        elif text[i] in "\"'":
            end = i + 1
            while end < len(text) and text[end] != text[i] and text[end] != "\n":
                end += 2 if text[end] == "\\" else 1
            end += 1
        else:
            out.append(text[i])
            i += 1
            continue
        out.append("".join(c if c == "\n" else " " for c in text[i:end]))
        i = end
    return "".join(out)


def unwrapped_addresses(text, release=None):
    """Hand-written C literals that would move in a release but skip BLACK_VA.

    Returns (line, literal) pairs. Every such value in recomp_manual.c and its
    includes is a canonical guest address, so it must be written BLACK_VA(...)
    to reach the right place in the PAL image.
    """
    release = release or PAL
    code = _mask_comments_and_strings(text)
    found = []
    for match in C_LITERAL.finditer(code):
        value = int(match[1], 16)
        try:
            moves = release.to_guest(value) != value
        except ValueError:
            moves = True  # inside the unresolved window: never guess
        if not moves or re.search(r"BLACK_VA\(\s*$", code[max(0, match.start() - 32):match.start()]):
            continue
        found.append((code.count("\n", 0, match.start()) + 1, match[0]))
    return found

NTSC = Release(
    name="ntsc",
    sha256="DF2739C372D254A90AEECCF5971D12097F22D89FBB90DB021FDA96DD4DEB68F6")

# European release, built 2006-01-09. .text grows by 0x30 bytes somewhere in
# the window below; every later section moves by 0x20. The window narrows to
# the exact point once it is located with find_pal_insertion.py against the
# NTSC XBE. No repository address falls inside it.
PAL = Release(
    name="pal",
    sha256="67F35121CCF622E7A293C402219596FE6456CA4C3D27E6F8139E449264DA30F0",
    text_cut_low=0x115B40,
    text_cut_high=0x1184D0,
    text_shift=0x30,
    post_shift=0x20,
    xbe_language_banks=("UK", "Fr", "Ge", "It", "Sp"))

RELEASES = {release.sha256: release for release in (NTSC, PAL)}


def detect(sha256):
    return RELEASES.get(sha256.upper())
